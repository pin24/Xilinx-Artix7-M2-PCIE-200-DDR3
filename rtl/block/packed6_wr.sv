// ============================================================================
// packed6_wr.sv - Barrel 8->6 для PACKED6: 48-бит результат -> 8-байт AXI-слово
// ----------------------------------------------------------------------------
// PACKED6 результат = 48 бит tf48 = 6 байт, в AXI-слово (8 байт) ложится
// байт-блочно с корректным WSTRB: 6 байт данных + 2 нуля (Design C.4).
//
// Модуль принимает ОДИН 48-бит результат и раскладывает его в 64-бит AXI-слово
// с заданным байтовым смещением `woff` внутри слова (0..2, чтобы 6 байт
// помещались в одно слово). Возвращает wdata (6 байт на позиции woff,
// остальное 0) и wstrb (6 единиц на позиции woff, остальное 0).
//
// Ограничение: для ОДНОГО слова результата woff + 6 <= 8 (woff<=2). Ядро
// требует word-выровненный result_addr (woff=0) - см. align_q в контроллере.
// ============================================================================
module packed6_wr #(
    parameter int SW     = 8,     // байт в AXI-слове
    parameter int BPE    = 6      // байт результат элементов
)(
    input  logic [47:0] res,      // tf48 результат (E в бит[47:40], M в [39:0])
    input  logic [2:0]  woff,     // байтовое смещение в слове (0..SW-BPE)
    output logic [63:0] wdata,    // 64-бит слово
    output logic [SW-1:0] wstrb   // байт-строб: BPE установленных бит от woff
);

    always_comb begin
        wdata = 64'h0;
        for (int i = 0; i < BPE; i = i + 1)
            wdata[ 8*(woff+i) +: 8 ] = res[ 8*i +: 8 ];
        wstrb = {SW{1'b0}};
        for (int i = 0; i < BPE; i = i + 1)
            wstrb[ woff + i ] = 1'b1;
    end

endmodule