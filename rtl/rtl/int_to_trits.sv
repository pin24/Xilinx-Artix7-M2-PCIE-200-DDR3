// ============================================================================
// int_to_trits.sv - конвертер целого (двоичного) в balanced ternary триты
// ============================================================================
// value (знаковый, W бит) -> N тритов (каждый 2 бита, старший первым).
// Стандартный алгоритм: пока v != 0: r = v mod 3; v = v/3 (floor);
//   если r == 2: r = -1, v += 1;  если r == -2: r = +1, v -= 1.
// (В SystemVerilog % для отрицательных даёт остаток со знаком делимого,
//  а / для отрицательных округляет к нулю - нужно аккуратно.)
// ============================================================================

module int_to_trits #(
    parameter int N = 15,   // число тритов
    parameter int W = 96    // ширина входного значения
)(
    input  logic signed [W-1:0] value,
    output logic [N*2-1:0]      trits
);

    logic signed [W-1:0] v;
    logic signed [W-1:0] q, r;
    logic [1:0] rcode;

    always_comb begin
        v = value;
        for (int i = N-1; i >= 0; i--) begin
            // деление с округлением к минус бесконечности (floor)
            // q = floor(v/3); r = v - 3*q  -> r in {0,1,2}
            q = (v >= 0) ? (v / 3) : -((-v + 2) / 3);
            r = v - 3 * q;
            // balanced: 0->00, 1->01, 2->10(-1) с переносом
            case (r)
                3'sd1: begin rcode = 2'b01; v = q; end
                3'sd2: begin rcode = 2'b10; v = q + 1; end  // -1, перенос +1
                default: begin rcode = 2'b00; v = q; end
            endcase
            // i=N-1 (первый остаток = младший) -> младший трит
            trits[(N-1-i)*2 +: 2] = rcode;
        end
    end

endmodule
